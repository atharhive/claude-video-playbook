#!/usr/bin/env python3
"""
Automated ElevenLabs and Neural Voiceover Generator
Generates studio vocal stems from narration/script.json and computes word timings.
"""

import asyncio, os, sys, json, subprocess, wave, argparse
from pathlib import Path

DEFAULT_VOICE = "en-US-ChristopherNeural"
SAMPLE_RATE = 48000

async def generate_edge_tts(text, voice, out_wav):
    import edge_tts
    tmp_mp3 = out_wav.with_suffix(".tmp.mp3")
    comm = edge_tts.Communicate(text, voice, rate="+3%")
    await comm.save(str(tmp_mp3))
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", str(tmp_mp3), "-ar", str(SAMPLE_RATE), "-ac", "1", str(out_wav)], check=True)
    tmp_mp3.unlink(missing_ok=True)

def generate_elevenlabs(text, voice_id, api_key, out_wav, model_id="eleven_flash_v2_5"):
    import urllib.request
    url = f"https://api.elevenlabs.io/v1/text-to-speech/{voice_id}"
    payload = json.dumps({
        "text": text,
        "model_id": model_id,
        "voice_settings": {
            "stability": 0.45,
            "similarity_boost": 0.85,
            "style": 0.35,
            "use_speaker_boost": True
        }
    }).encode("utf-8")

    req = urllib.request.Request(url, data=payload, headers={
        "xi-api-key": api_key,
        "Content-Type": "application/json",
        "Accept": "audio/mpeg"
    })

    tmp_mp3 = out_wav.with_suffix(".tmp.mp3")
    with urllib.request.urlopen(req) as resp:
        tmp_mp3.write_bytes(resp.read())

    subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", str(tmp_mp3), "-ar", str(SAMPLE_RATE), "-ac", "1", str(out_wav)], check=True)
    tmp_mp3.unlink(missing_ok=True)

def main():
    parser = argparse.ArgumentParser(description="Generate voiceover lines from script.json.")
    parser.add_argument("--script", default="narration/script.json", help="Path to script.json")
    parser.add_argument("--out-dir", default="narration/voice/final_narrator", help="Output directory for audio files")
    parser.add_argument("--provider", choices=["edge", "elevenlabs"], default="edge", help="TTS provider")
    parser.add_argument("--voice", default=DEFAULT_VOICE, help="Voice name or ElevenLabs voice ID")

    args = parser.parse_args()
    script_path = Path(args.script)
    if not script_path.exists():
        print(f"Error: Script file not found at {script_path}")
        sys.exit(1)

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    script = json.loads(script_path.read_text(encoding="utf-8"))
    api_key = os.environ.get("ELEVENLABS_API_KEY", "")
    if args.provider == "elevenlabs" and not api_key:
        print("Warning: ELEVENLABS_API_KEY not set. Falling back to edge-tts.")
        args.provider = "edge"

    seg = {}
    print(f"[*] Generating {len(script)} lines with {args.provider}...")

    for item in script:
        lid = item["id"]
        text = item["text"]
        out_wav = out_dir / f"{lid}.wav"

        if args.provider == "elevenlabs":
            generate_elevenlabs(text, args.voice, api_key, out_wav)
        else:
            asyncio.run(generate_edge_tts(text, args.voice, out_wav))

        with wave.open(str(out_wav), "rb") as w:
            dur = w.getnframes() / w.getframerate()

        words = text.split()
        weights = [len(x) + 2 for x in words]
        total_w = sum(weights)
        t = 0.0
        word_spans = []
        for x, wt in zip(words, weights):
            d = dur * wt / total_w
            word_spans.append({"w": x, "s": round(t, 3), "e": round(t + d, 3)})
            t += d

        seg[lid] = {
            "dur": round(dur, 3),
            "file": f"voice/final_narrator/{lid}.wav",
            "words": word_spans
        }
        print(f"  [+] {lid} ({dur:.2f}s): {text[:40]}...")

    timing_file = script_path.parent / "timing_narrator.js"
    timing_file.write_text("// generated by build_voiceover.py\nconst VO = " + json.dumps({"order": [l["id"] for l in script], "seg": seg}) + ";\n")
    print(f"[✓] Completed narration generation. Timings written to {timing_file}")

if __name__ == "__main__":
    main()
